//! Android USB attach filter rendered from the catalog, not a second device list.

use super::SUPPORTED_DEVICES;
use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write;

/// The `res/xml` filter Android matches on `USB_DEVICE_ATTACHED`. Plugging in
/// a listed DAC offers to open Glacier EQ, which then has USB permission.
pub fn usb_device_filter() -> String {
    let mut vendors: BTreeMap<u16, BTreeSet<Option<u16>>> = BTreeMap::new();
    for profile in SUPPORTED_DEVICES {
        vendors
            .entry(profile.vendor_id)
            .or_default()
            .insert(profile.product_id);
    }
    let mut xml = String::from(
        "<?xml version=\"1.0\" encoding=\"utf-8\"?>\n\
         <!-- Glacier EQ USB DAC filter for USB_DEVICE_ATTACHED.\n     \
         Generated by glacier-eq-cli android-usb-filter from device/catalog.rs.\n     \
         IDs are decimal. A catalog vendor fallback matches all its PIDs. -->\n\
         <resources>\n",
    );
    for (vendor, products) in vendors {
        if products.contains(&None) {
            writeln!(
                xml,
                "    <usb-device vendor-id=\"{vendor}\" /> <!-- {vendor:04x}:* -->"
            )
            .unwrap();
        } else {
            for product in products.into_iter().flatten() {
                writeln!(
                    xml,
                    "    <usb-device vendor-id=\"{vendor}\" product-id=\"{product}\" /> <!-- {vendor:04x}:{product:04x} -->"
                )
                .unwrap();
            }
        }
    }
    xml.push_str("</resources>\n");
    xml
}

#[cfg(test)]
mod tests {
    #[test]
    fn shipped_filter_is_current() {
        assert_eq!(
            super::usb_device_filter(),
            include_str!("../../../scripts/android/usb_device_filter.xml"),
            "regenerate with cargo run -p glacier-core --bin glacier-eq-cli -- android-usb-filter > scripts/android/usb_device_filter.xml"
        );
    }

    #[test]
    fn manifest_opens_the_app_for_listed_dacs_only_when_opted_in() {
        let manifest = include_str!("../../../scripts/android/usb-attach-launcher.xml");
        // The release overlay must restore this alias after Tauri regenerates
        // its manifest; HidPlugin enables it by name and it must ship disabled.
        let alias = manifest
            .split("<activity-alias")
            .nth(1)
            .and_then(|rest| rest.split("</activity-alias>").next())
            .expect("USB attach alias");
        assert!(alias.contains("android:name=\".UsbAttachLauncher\""));
        assert!(alias.contains("android:enabled=\"false\""));
        assert!(alias.contains("android.hardware.usb.action.USB_DEVICE_ATTACHED"));
        assert!(alias.contains("@xml/usb_device_filter"));
        assert_eq!(manifest.matches("USB_DEVICE_ATTACHED\" />").count(), 1);
    }
}
