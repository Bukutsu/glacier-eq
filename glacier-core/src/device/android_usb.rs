//! Android USB attach filter rendered from the catalog, not a second device list.

use super::SUPPORTED_DEVICES;
use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write;

/// The `res/xml` filter Android matches on `USB_DEVICE_ATTACHED`. Plugging in
/// a listed DAC offers to open Glacier EQ, which then has USB permission.
pub fn usb_device_filter() -> String {
    let mut vendors: BTreeMap<u16, BTreeSet<Option<u16>>> = BTreeMap::new();
    for profile in SUPPORTED_DEVICES {
        vendors
            .entry(profile.vendor_id)
            .or_default()
            .insert(profile.product_id);
    }
    let mut xml = String::from(
        "<?xml version=\"1.0\" encoding=\"utf-8\"?>\n\
         <!-- Glacier EQ USB DAC filter for USB_DEVICE_ATTACHED.\n     \
         Generated by glacier-eq-cli android-usb-filter from device/catalog.rs.\n     \
         IDs are decimal. A catalog vendor fallback matches all its PIDs. -->\n\
         <resources>\n",
    );
    for (vendor, products) in vendors {
        if products.contains(&None) {
            writeln!(
                xml,
                "    <usb-device vendor-id=\"{vendor}\" /> <!-- {vendor:04x}:* -->"
            )
            .unwrap();
        } else {
            for product in products.into_iter().flatten() {
                writeln!(
                    xml,
                    "    <usb-device vendor-id=\"{vendor}\" product-id=\"{product}\" /> <!-- {vendor:04x}:{product:04x} -->"
                )
                .unwrap();
            }
        }
    }
    xml.push_str("</resources>\n");
    xml
}
