//! Linux access rules rendered from the catalog, not a second device list.

use super::SUPPORTED_DEVICES;
use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write;

pub fn rules() -> String {
    let mut vendors: BTreeMap<u16, BTreeSet<Option<u16>>> = BTreeMap::new();
    for profile in SUPPORTED_DEVICES {
        vendors
            .entry(profile.vendor_id)
            .or_default()
            .insert(profile.product_id);
    }
    let mut rules = String::from(
        "# Glacier EQ USB DAC udev rules\n\
         # Generated by glacier-eq-cli udev-rules from device/catalog.rs.\n\
         # Active-seat access only. A catalog vendor fallback grants all its PIDs.\n\n",
    );
    for (vendor, products) in vendors {
        if products.contains(&None) {
            writeln!(rules, "KERNEL==\"hidraw*\", SUBSYSTEM==\"hidraw\", ATTRS{{idVendor}}==\"{vendor:04x}\", TAG+=\"uaccess\"").unwrap();
        } else {
            for product in products.into_iter().flatten() {
                writeln!(rules, "KERNEL==\"hidraw*\", SUBSYSTEM==\"hidraw\", ATTRS{{idVendor}}==\"{vendor:04x}\", ATTRS{{idProduct}}==\"{product:04x}\", TAG+=\"uaccess\"").unwrap();
            }
        }
    }
    rules
}

#[cfg(test)]
mod tests {
    #[test]
    fn shipped_rules_are_current() {
        assert_eq!(
            super::rules(),
            include_str!("../../../udev/69-glacier-eq.rules"),
            "regenerate with cargo run -p glacier-core --bin glacier-eq-cli -- udev-rules > udev/69-glacier-eq.rules"
        );
    }
}
